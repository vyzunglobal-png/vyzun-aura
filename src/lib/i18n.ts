export const LANGUAGES = [
  { code: "en", label: "English" },
  { code: "hi", label: "हिन्दी" },
  { code: "es", label: "Español" },
  { code: "fr", label: "Français" },
  { code: "de", label: "Deutsch" },
  { code: "it", label: "Italiano" },
  { code: "pt", label: "Português" },
  { code: "ar", label: "العربية" },
  { code: "ja", label: "日本語" },
  { code: "ko", label: "한국어" },
  { code: "zh", label: "中文" },
  { code: "ru", label: "Русский" },
] as const;

export type LanguageCode = (typeof LANGUAGES)[number]["code"];

export const DICTIONARIES: Record<LanguageCode, Dict> = { en, hi, es, fr, de, it, pt, ar, ja, ko, zh, ru };

export const RTL_LANGUAGES: readonly string[] = ["ar"];

export function resolveLanguage(code: string | null | undefined): LanguageCode {
  const base = (code ?? "en").toLowerCase().split("-")[0] ?? "en";
  return (base in DICTIONARIES ? base : "en") as LanguageCode;
}

export function translate(language: string | null | undefined, key: I18nKey): string {
  return DICTIONARIES[resolveLanguage(language)][key] ?? en[key];
}

export function isRtl(language: string | null | undefined): boolean {
  return RTL_LANGUAGES.includes(resolveLanguage(language));
}
